import {Router} from 'express';
import rateLimit from 'express-rate-limit';
import * as c from '../controllers/doctorClinicalRecordsController.js';
import * as chart from '../controllers/doctorDentalChartController.js';
import * as images from '../controllers/doctorClinicalImageController.js';
import {authenticateToken} from '../middleware/authenticateToken.js';
import {requireRole} from '../middleware/requireRole.js';
import {validateRequest} from '../middleware/validateRequest.js';
import {clinicalImageUpload} from '../middleware/clinicalImageUpload.js';
import {asyncHandler} from '../utils/asyncHandler.js';
import {amendmentRules,clinicalProfileRules,instructionIdRules,instructionRules,noteRules,patientIdRules} from '../validators/clinicalRecordsValidators.js';
import {amendChartEntryRules,chartPatientRules,createChartEntryRules} from '../validators/dentalChartValidators.js';
import {imageIdRules,imageListRules,imagePatientRules,imageUploadRules} from '../validators/clinicalImageValidators.js';
const r=Router();
const uploadLimit=rateLimit({windowMs:15*60*1000,limit:20,standardHeaders:'draft-8',legacyHeaders:false});
r.use(authenticateToken,requireRole('Doctor'));
r.get('/patients',asyncHandler(c.patients));
r.get('/patients/:patientId/record',patientIdRules,validateRequest,asyncHandler(c.record));
r.get('/patients/:patientId/dental-chart',chartPatientRules,validateRequest,asyncHandler(chart.chart));
r.get('/patients/:patientId/dental-chart/history',chartPatientRules,validateRequest,asyncHandler(chart.history));
r.post('/patients/:patientId/dental-chart/entries',createChartEntryRules,validateRequest,asyncHandler(chart.create));
r.post('/patients/:patientId/dental-chart/entries/:entryId/amend',amendChartEntryRules,validateRequest,asyncHandler(chart.amend));
r.get('/patients/:patientId/clinical-images',imageListRules,validateRequest,asyncHandler(images.list));
r.post('/patients/:patientId/clinical-images',uploadLimit,imagePatientRules,validateRequest,clinicalImageUpload,imageUploadRules,validateRequest,asyncHandler(images.upload));
r.get('/patients/:patientId/clinical-images/:imageId/content',imageIdRules,validateRequest,asyncHandler(images.content));
r.post('/patients/:patientId/clinical-images/:imageId/archive',imageIdRules,validateRequest,asyncHandler(images.archive));
r.patch('/patients/:patientId/clinical-profile',clinicalProfileRules,validateRequest,asyncHandler(c.updateProfile));
r.post('/patients/:patientId/clinical-notes',noteRules,validateRequest,asyncHandler(c.addNote));
r.post('/patients/:patientId/clinical-notes/:noteId/amend',amendmentRules,validateRequest,asyncHandler(c.amend));
r.post('/patients/:patientId/instructions',instructionRules,validateRequest,asyncHandler(c.createInstruction));
r.post('/patients/:patientId/instructions/:instructionId/publish',instructionIdRules,validateRequest,asyncHandler(c.publishInstruction));
r.post('/patients/:patientId/instructions/:instructionId/withdraw',instructionIdRules,validateRequest,asyncHandler(c.withdrawInstruction));
export default r;
