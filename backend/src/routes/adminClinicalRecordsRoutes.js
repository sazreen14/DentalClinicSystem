import {Router} from 'express';
import {authenticateToken} from '../middleware/authenticateToken.js';
import {requireRole} from '../middleware/requireRole.js';
import {validateRequest} from '../middleware/validateRequest.js';
import {asyncHandler} from '../utils/asyncHandler.js';
import * as c from '../controllers/adminClinicalRecordsController.js';
import * as chart from '../controllers/adminDentalChartController.js';
import * as images from '../controllers/adminClinicalImageController.js';
import {patientIdRules} from '../validators/clinicalRecordsValidators.js';
import {chartPatientRules} from '../validators/dentalChartValidators.js';
import {imageIdRules,imageListRules} from '../validators/clinicalImageValidators.js';
const r=Router();r.use(authenticateToken,requireRole('Admin'));
r.get('/',asyncHandler(c.list));
r.get('/:patientId/dental-chart',chartPatientRules,validateRequest,asyncHandler(chart.chart));
r.get('/:patientId/dental-chart/history',chartPatientRules,validateRequest,asyncHandler(chart.history));
r.get('/:patientId/clinical-images',imageListRules,validateRequest,asyncHandler(images.list));
r.get('/:patientId/clinical-images/:imageId/content',imageIdRules,validateRequest,asyncHandler(images.content));
r.get('/:patientId',patientIdRules,validateRequest,asyncHandler(c.record));
export default r;
