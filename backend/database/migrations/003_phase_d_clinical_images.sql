CREATE TABLE IF NOT EXISTS clinical_images (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  image_id VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  patient_id BIGINT UNSIGNED NOT NULL,
  clinical_record_id BIGINT UNSIGNED NOT NULL,
  appointment_id BIGINT UNSIGNED NULL,
  doctor_id BIGINT UNSIGNED NOT NULL,
  storage_provider VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'private-filesystem',
  storage_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  original_filename VARCHAR(180) NOT NULL,
  mime_type ENUM('image/jpeg','image/png','image/webp') NOT NULL,
  byte_size BIGINT UNSIGNED NOT NULL,
  sha256_checksum CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  caption_ciphertext MEDIUMTEXT NULL,
  encryption_key_version SMALLINT UNSIGNED NULL,
  status ENUM('Active','Archived') NOT NULL DEFAULT 'Active',
  archived_by_user_id BIGINT UNSIGNED NULL,
  archived_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_clinical_images_patient FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_clinical_images_record FOREIGN KEY (clinical_record_id) REFERENCES clinical_records(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_clinical_images_appointment FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_clinical_images_doctor FOREIGN KEY (doctor_id) REFERENCES doctors(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_clinical_images_archiver FOREIGN KEY (archived_by_user_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT chk_clinical_images_size CHECK (byte_size > 0),
  INDEX idx_clinical_images_patient_status_created (patient_id,status,created_at),
  INDEX idx_clinical_images_record_created (clinical_record_id,created_at),
  INDEX idx_clinical_images_patient_checksum (patient_id,sha256_checksum)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
